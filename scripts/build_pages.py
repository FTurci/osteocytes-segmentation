"""Generate one page per data/<tag>/ (series/<tag>.qmd) and the series table on the index page.

Run by import_series.py; run it directly after editing data/ by hand. The generated files are tracked in git,
so a fresh clone renders with plain `quarto render`.

Standard library only, so any python3 can render the site.
"""
import csv
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
PAGES = ROOT / "series"

TABLE_COLUMNS = [
    ("label", "label"), ("volume_um3", "volume (µm³)"), ("surface_area_um2", "surface (µm²)"),
    ("axis_1_um", "axis 1 (µm)"), ("axis_2_um", "axis 2 (µm)"), ("axis_3_um", "axis 3 (µm)"),
    ("flatness", "flatness"), ("n_nuclei", "nuclei"), ("nucleus_volume_um3", "nucleus (µm³)"),
    ("n_dendrites", "dendrites"), ("mean_dendrite_reach_um", "reach mean (µm)"),
    ("std_dendrite_reach_um", "reach sd (µm)"), ("max_dendrite_reach_um", "reach max (µm)"),
    ("mean_dendrite_path_um", "path mean (µm)"),
]


def fmt(value):
    try:
        x = float(value)
    except ValueError:
        return html.escape(value)
    if x != x:
        return ""
    return f"{x:.0f}" if x.is_integer() or abs(x) >= 100 else f"{x:.2f}"


def read_csv(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def html_table(rows, columns, css_class="datatable"):
    head = "".join(f"<th>{html.escape(title)}</th>" for _, title in columns)
    body = "\n".join("<tr>" + "".join(f"<td>{fmt(r.get(key, ''))}</td>" for key, _ in columns) + "</tr>" for r in rows)
    return f'<table class="{css_class}">\n<thead><tr>{head}</tr></thead>\n<tbody>\n{body}\n</tbody>\n</table>'


def viewer(src, alt, nucleus_opacity):
    return (f'<button class="btn btn-sm btn-outline-secondary nuclei-toggle" aria-pressed="true" '
            f'data-target="scene" data-opacity="{nucleus_opacity}">Nuclei: shown</button>\n'
            f'<model-viewer id="scene" src="{src}" alt="{html.escape(alt)}" camera-controls touch-action="pan-y" '
            f'interaction-prompt="none" shadow-intensity="0" exposure="1.1" class="scene-viewer" '
            f'camera-orbit="0deg 35deg auto"></model-viewer>')


def gallery(tag, rows):
    cards = []
    for r in rows:
        label = r["label"]
        cell = DATA / tag / "cells"
        image = next((f"osteocyte_{label}{s}" for s in ("_rotation.gif", "_mip.png") if (cell / f"osteocyte_{label}{s}").exists()), None)
        picture = (f'<img src="../data/{tag}/cells/{image}" loading="lazy" alt="osteocyte {label}">' if image
                   else '<div class="no-image">no rendering</div>')
        caption = f"#{label} · {fmt(r['volume_um3'])} µm³ · {r['n_dendrites']} dendrites"
        cards.append(f'<figure class="cell-card" data-glb="../data/{tag}/cells/osteocyte_{label}.glb" '
                     f'data-title="osteocyte {label}">{picture}<figcaption>{caption}</figcaption></figure>')
    return '<div class="gallery">\n' + "\n".join(cards) + "\n</div>"


def series_page(tag, meta, rows):
    vs, shape = meta["voxel_size_um"], meta["shape_zyx"]
    extent = " × ".join(f"{n * vs:.0f}" for n in shape)
    counts = "\n".join(f"| {html.escape(k)} | {v} |" for k, v in meta["counts"].items())
    downloads = [f"[{name}](../data/{tag}/{name})" for name in
                 ["osteocyte_props.csv", "dendrites.csv", "summary.log", "summary.json", "scene.glb", "scene_obj.zip"]
                 if (DATA / tag / name).exists()]
    return f"""---
title: "{meta['series']}"
---

<!-- generated by scripts/build_pages.py from data/{tag}/; edits are overwritten -->

Voxel size {vs:.4f} µm (cubic) · volume {shape[0]} × {shape[1]} × {shape[2]} voxels (z, y, x) = {extent} µm ·
exported {meta['written'][:10]} from `{meta['file']}`.

Downloads: {" · ".join(downloads)}

## 3D scene

Drag to rotate, scroll to zoom, right-drag to pan. One colour per osteocyte; cleaned ch0 nuclei inside the hull
(bone side) in translucent blue. Depth (z) points up. `scene_obj.zip` has the same scene as OBJ + MTL in µm,
with and without the nuclei.

```{{=html}}
{viewer(f"../data/{tag}/scene.glb", f"{meta['series']} osteocytes and nuclei", meta['parameters']['NUCLEUS_OPACITY'])}
```

## Pipeline counts

| stage | count |
|:--|--:|
{counts}

## Osteocytes

```{{=html}}
{html_table(rows, TABLE_COLUMNS)}
```

## Gallery

Rotating maximum-intensity projections of ch1 inside each osteocyte. Click a cell for its 3D mesh.

```{{=html}}
{gallery(tag, rows)}
<dialog id="cell-dialog"><form method="dialog"><button class="close" aria-label="close">×</button></form>
<h3 class="cell-title"></h3><model-viewer camera-controls interaction-prompt="none" shadow-intensity="0" class="cell-viewer"></model-viewer></dialog>
```
"""


def write_csv(path, rows):
    columns = list(dict.fromkeys(k for r in rows for k in r))
    with open(path, "w", newline="") as f:
        writer = csv.DictWriter(f, columns)
        writer.writeheader()
        writer.writerows(rows)


def write_aggregate(series):
    """data/aggregate/: every series pooled, for the analysis page (one row per osteocyte / dendrite / series)."""
    out = DATA / "aggregate"
    out.mkdir(exist_ok=True)
    write_csv(out / "osteocytes.csv", [r for tag, _ in series for r in read_csv(DATA / tag / "osteocyte_props.csv")])
    write_csv(out / "dendrites.csv", [r for tag, _ in series for r in read_csv(DATA / tag / "dendrites.csv")])
    write_csv(out / "series.csv", [dict(
        series=m["series"], tag=tag, voxel_size_um=m["voxel_size_um"], osteocytes=m["counts"]["surviving osteocytes"],
        dendrites=m["n_dendrites"], nuclei_in_hull=m["counts"]["inside hull, bone side"],
        detected=m["counts"]["detected"], labelled_rejected=m["counts"]["labelled, rejected"],
        no_ch1=m["counts"]["no ch1 label"], soft_tissue=m["counts"]["soft tissue"]) for tag, m in series])


def main():
    PAGES.mkdir(exist_ok=True)
    for stale in PAGES.glob("*.qmd"):
        stale.unlink()
    index_rows, series = [], []
    for summary in sorted(DATA.glob("*/summary.json")):
        tag = summary.parent.name
        meta = json.loads(summary.read_text())
        series.append((tag, meta))
        rows = read_csv(summary.parent / "osteocyte_props.csv")
        (PAGES / f"{tag}.qmd").write_text(series_page(tag, meta, rows))
        c = meta["counts"]
        index_rows.append(dict(
            series=f'<a href="series/{tag}.html">{html.escape(meta["series"])}</a>',
            osteocytes=c["surviving osteocytes"], dendrites=meta["n_dendrites"],
            nuclei=c["inside hull, bone side"],
            unlabelled=c["inside hull, not labelled as osteocyte (rejected + no ch1)"],
            voxel=f'{meta["voxel_size_um"]:.4f}', exported=meta["written"][:10]))
    columns = [("series", "series"), ("osteocytes", "osteocytes"), ("dendrites", "dendrites"),
               ("nuclei", "nuclei in hull"), ("unlabelled", "nuclei not labelled"),
               ("voxel", "voxel (µm)"), ("exported", "exported")]
    head = "".join(f"<th>{t}</th>" for _, t in columns)
    body = "\n".join("<tr>" + "".join(f"<td>{r[k]}</td>" for k, _ in columns) + "</tr>" for r in index_rows)
    (ROOT / "_series_index.md").write_text(
        f"```{{=html}}\n<table class=\"datatable\">\n<thead><tr>{head}</tr></thead>\n<tbody>\n{body}\n</tbody>\n</table>\n```\n")
    write_aggregate(series)
    print(f"built {len(index_rows)} series pages and data/aggregate/")


if __name__ == "__main__":
    main()
